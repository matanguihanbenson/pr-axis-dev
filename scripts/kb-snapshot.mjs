#!/usr/bin/env node
/**
 * Refreshes the Ask Marcus knowledge base snapshot from the canonical KB API.
 *
 * The API (matanguihanbenson/pr-axis-kb-api) is the source of truth. This
 * script pulls every entry, then writes:
 *
 *   content/ask-marcus/<topic>.md        human-readable snapshot, one file per topic
 *   lib/ask-marcus/kb-snapshot.json      bundled fallback the API route imports
 *
 * Run it after any KB change: `node scripts/kb-snapshot.mjs`
 * Nothing is written if the fetch fails, so a bad network call cannot wipe the
 * fallback.
 */

import { mkdir, writeFile, rename, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const BASE =
  process.env.KB_API_URL ||
  "https://pr-axis-kb-api-matanguihanbensons-projects.vercel.app";
const ROOT = process.cwd();
const MD_DIR = join(ROOT, "content", "ask-marcus");
const JSON_PATH = join(ROOT, "lib", "ask-marcus", "kb-snapshot.json");

const TOPIC_ORDER = [
  "services",
  "packages",
  "pricing-rules",
  "custom-builds",
  "process",
  "faqs",
];

const TOPIC_TITLES = {
  services: "Services",
  packages: "Packages",
  "pricing-rules": "Pricing rules",
  "custom-builds": "Custom builds",
  process: "Process",
  faqs: "FAQs",
};

function sortEntries(entries) {
  return [...entries].sort((a, b) => a.id.localeCompare(b.id));
}

function topicFile(topic, entries) {
  const head = [
    `# ${TOPIC_TITLES[topic] || topic}`,
    "",
    "<!-- generated by scripts/kb-snapshot.mjs from the KB API, do not edit by hand -->",
    "",
  ].join("\n");

  const body = sortEntries(entries)
    .map((entry) =>
      [
        `## ${entry.title}`,
        "",
        `- id: ${entry.id}`,
        `- keywords: ${entry.keywords.join(", ")}`,
        `- source: ${entry.source}`,
        "",
        entry.answer,
        "",
      ].join("\n"),
    )
    .join("\n");

  return head + body;
}

async function writeAtomic(path, contents) {
  const temp = `${path}.tmp`;
  await writeFile(temp, contents, "utf8");
  await rename(temp, path);
}

async function main() {
  const url = `${BASE.replace(/\/$/, "")}/api/kb`;
  const response = await fetch(url, {
    headers: { accept: "application/json" },
    signal: AbortSignal.timeout(20_000),
  });

  if (!response.ok) {
    throw new Error(`KB API returned ${response.status} for ${url}`);
  }

  const payload = await response.json();
  const entries = Array.isArray(payload.entries) ? payload.entries : null;

  if (!entries || entries.length === 0) {
    throw new Error("KB API returned no entries, snapshot left untouched");
  }

  for (const entry of entries) {
    for (const field of ["id", "topic", "title", "answer", "source"]) {
      if (!entry[field]) {
        throw new Error(`KB entry is missing "${field}": ${JSON.stringify(entry).slice(0, 120)}`);
      }
    }
    if (!Array.isArray(entry.keywords)) entry.keywords = [];
  }

  const byTopic = new Map();
  for (const entry of entries) {
    if (!byTopic.has(entry.topic)) byTopic.set(entry.topic, []);
    byTopic.get(entry.topic).push(entry);
  }

  await mkdir(MD_DIR, { recursive: true });
  await mkdir(dirname(JSON_PATH), { recursive: true });

  const topics = [...byTopic.keys()].sort((a, b) => {
    const ai = TOPIC_ORDER.indexOf(a);
    const bi = TOPIC_ORDER.indexOf(b);
    return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi) || a.localeCompare(b);
  });

  for (const topic of topics) {
    await writeAtomic(
      join(MD_DIR, `${topic}.md`),
      topicFile(topic, byTopic.get(topic)),
    );
  }

  const snapshot = {
    generated_at: new Date().toISOString(),
    source: url,
    entries: entries.map((entry) => ({
      id: entry.id,
      topic: entry.topic,
      title: entry.title,
      keywords: entry.keywords,
      answer: entry.answer,
      source: entry.source,
    })),
  };

  await writeAtomic(JSON_PATH, `${JSON.stringify(snapshot, null, 2)}\n`);

  const counts = topics.map((topic) => `${topic}: ${byTopic.get(topic).length}`);
  console.log(`Wrote ${entries.length} entries (${counts.join(", ")})`);
  console.log(`Markdown: ${MD_DIR}`);
  console.log(`Bundled fallback: ${JSON_PATH}`);

  // A previous snapshot that never produced a file is a bug worth surfacing.
  await readFile(JSON_PATH, "utf8");
}

main().catch((error) => {
  console.error(`Snapshot failed: ${error.message}`);
  process.exit(1);
});
