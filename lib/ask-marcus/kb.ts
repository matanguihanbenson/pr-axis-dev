import snapshot from "./kb-snapshot.json";

export type KbEntry = {
  id: string;
  topic: string;
  title: string;
  keywords: string[];
  answer: string;
  source: string;
};

type Snapshot = { entries: KbEntry[] };

const SNAPSHOT = (snapshot as Snapshot).entries;

const KB_API_URL = (
  process.env.KB_API_URL ||
  "https://pr-axis-kb-api-matanguihanbensons-projects.vercel.app"
).replace(/\/$/, "");

const API_TTL_MS = 5 * 60 * 1000;
const FALLBACK_TTL_MS = 60 * 1000;

type Cache = { entries: KbEntry[]; from: "api" | "snapshot"; at: number };

let cache: Cache | null = null;

function isEntry(value: unknown): value is KbEntry {
  if (!value || typeof value !== "object") return false;
  const entry = value as Record<string, unknown>;
  return (
    typeof entry.id === "string" &&
    typeof entry.topic === "string" &&
    typeof entry.title === "string" &&
    typeof entry.answer === "string" &&
    typeof entry.source === "string" &&
    Array.isArray(entry.keywords)
  );
}

/**
 * The KB API is canonical. The bundled snapshot (generated by
 * scripts/kb-snapshot.mjs) is the fallback when the API cannot be reached, so
 * the chatbot never breaks.
 */
export async function loadKb(): Promise<{
  entries: KbEntry[];
  from: "api" | "snapshot";
}> {
  const fresh =
    cache &&
    Date.now() - cache.at < (cache.from === "api" ? API_TTL_MS : FALLBACK_TTL_MS);
  if (cache && fresh) return { entries: cache.entries, from: cache.from };

  try {
    const response = await fetch(`${KB_API_URL}/api/kb`, {
      headers: { accept: "application/json" },
      cache: "no-store",
      signal: AbortSignal.timeout(2500),
    });
    if (!response.ok) throw new Error(`KB API ${response.status}`);
    const payload = (await response.json()) as { entries?: unknown };
    const entries = Array.isArray(payload.entries)
      ? payload.entries.filter(isEntry)
      : [];
    if (entries.length === 0) throw new Error("KB API returned no entries");
    cache = { entries, from: "api", at: Date.now() };
    return { entries, from: "api" };
  } catch {
    cache = { entries: SNAPSHOT, from: "snapshot", at: Date.now() };
    return { entries: SNAPSHOT, from: "snapshot" };
  }
}

export function normalize(text: string) {
  return ` ${text
    .toLowerCase()
    .replace(/[^a-z0-9/+.\s-]/g, " ")
    .replace(/[.]/g, " ")
    .replace(/\s+/g, " ")
    .trim()} `;
}

export type KbMatch = { entry: KbEntry; score: number };

/**
 * Keyword search over the small KB. No model, no embeddings, no cost.
 * A keyword phrase is scored by its word count, so "who are you" outranks "you".
 */
export function searchKb(entries: KbEntry[], message: string): KbMatch[] {
  const text = normalize(message);
  const matches: KbMatch[] = [];

  for (const entry of entries) {
    let score = 0;
    for (const keyword of entry.keywords) {
      const phrase = normalize(keyword).trim();
      if (!phrase) continue;
      if (text.includes(` ${phrase} `)) {
        score += 3 * phrase.split(" ").length;
      }
    }
    if (score > 0) matches.push({ entry, score });
  }

  return matches.sort((a, b) => b.score - a.score).slice(0, 4);
}

/** The "What moves the price" sentence from a service entry, if it has one. */
export function moversFrom(entry: KbEntry | undefined) {
  if (!entry) return null;
  const index = entry.answer.indexOf("What moves the price:");
  if (index === -1) return null;
  return entry.answer.slice(index).trim();
}
